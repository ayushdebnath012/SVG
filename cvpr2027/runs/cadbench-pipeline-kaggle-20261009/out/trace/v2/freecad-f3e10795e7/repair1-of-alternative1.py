import FreeCAD as App
import Part
import os
from pathlib import Path

# Create a new document
doc = App.newDocument("Part")

# Create the Body
body = doc.addObject("PartDesign::Body", "Body")
# In FreeCAD 1.1, Body.Placement is a PropertyPlacement, not a simple assignment in some contexts, 
# but usually App.Placement works. If not, we set it via the property tree logic or default.
# The error "empty parameter list..." suggests a type mismatch. 
# We will ensure the placement is set correctly.
body.Placement = App.Placement(App.Vector(0, 0, 0))

# --- Geometry Construction ---

# Step 1: Create the profile sketch (Frustum side profile)
# We create a sketch object inside the body.
sketch = body.newObject("Sketcher::SketchObject", "FrustumProfile")
# Attach to XY Plane. In FreeCAD 1.1, the plane object is usually named "XY_Plane" or similar.
# We can find it or use the default.
# Let's try to attach to the standard XY plane.
try:
    xy_plane = doc.getObject("XY_Plane")
    if not xy_plane:
        # Fallback: Create a plane if it doesn't exist (though standard docs usually have it)
        # Actually, for PartDesign::SketchObject, we can often just set the Placement and let it default,
        # or explicitly create a Part::Plane.
        # Let's create a plane to be safe and explicit.
        plane = doc.addObject("Part::Plane", "XY_Plane")
        plane.Placement = App.Placement(App.Vector(0, 0, 0))
        xy_plane = plane
except:
    pass

sketch.Placement = App.Placement(App.Vector(0, 0, 0))
# MapMode FlatFace is default. We need to ensure it attaches to the face of the plane.
# In FreeCAD 1.1, Sketcher::SketchObject has an AttachmentSupport property.
# We set the support to the plane object.
sketch.AttachmentSupport = (xy_plane, [""])

# Dimensions
top_diameter = 15.0
bottom_diameter = 25.0
height = 30.0
radius_top = top_diameter / 2.0
radius_bottom = bottom_diameter / 2.0

# Geometry: We will draw a closed shape consisting of two lines and a circle arc? 
# No, a frustum is generated by revolving a trapezoid around an axis.
# We will sketch a trapezoid on the XY plane, where the X-axis is the axis of revolution.
# Center point at (0,0), Top radius at y=Height/2? No, standard is usually Z-up.
# Let's rotate the sketch so the axis of revolution is the Y-axis of the sketch, 
# and we revolve around the Y-axis of the global coordinate system.
# Actually, simpler: Sketch on XY plane. Axis of revolution is the Y-axis (vertical in sketch).
# The profile is a trapezoid defined by:
# 1. Point at (0, 0) -> Center bottom
# 2. Point at (Radius_Bottom, 0)
# 3. Point at (Radius_Top, Height)
# 4. Point at (0, Height) -> Center top
# Then close the loop.

# Add Line Segments to the sketch
# Line 1: Bottom radius (X-axis)
p0 = App.Vector(0, 0, 0)
p1 = App.Vector(radius_bottom, 0, 0)
sketch.addGeometry(Part.LineSegment(p0, p1), False)

# Line 2: Slanted side (Frustum wall)
p2 = App.Vector(radius_top, height, 0)
sketch.addGeometry(Part.LineSegment(p1, p2), False)

# Line 3: Top radius (back to center)
p3 = App.Vector(0, height, 0)
sketch.addGeometry(Part.LineSegment(p2, p3), False)

# Line 4: Close the loop (center height to center bottom)
sketch.addGeometry(Part.LineSegment(p3, p0), False)

# Constraints: Make it symmetric and fixed
# 1. Point 0 at Origin
con0 = Sketcher.Constraint("Point", 0, 1, 0)
con1 = Sketcher.Constraint("Point", 1, 1, 0)
con2 = Sketcher.Constraint("Point", 2, 1, 0)
con3 = Sketcher.Constraint("Point", 3, 1, 0)

# 2. Coincident points on the axis (X=0)
con_c1 = Sketcher.Constraint("Point", 0, 1, 2) # X=0 for p0
con_c2 = Sketcher.Constraint("Point", 3, 1, 2) # X=0 for p3

# Add constraints
sketch.addConstraint(con0)
sketch.addConstraint(con1)
sketch.addConstraint(con2)
sketch.addConstraint(con3)
sketch.addConstraint(con_c1)
sketch.addConstraint(con_c2)

# Step 2: Revolution
# Reference axis: Y-Axis (since our sketch is on XY, and the line goes from 0 to Height on Y)
# Wait, in FreeCAD Sketcher on XY plane:
# X is horizontal, Y is vertical.
# Our points: (0,0) to (R_bot, 0) to (R_top, H) to (0, H).
# The axis of revolution should be the Y-axis.
rev = body.newObject("PartDesign::Revolution", "FrustumRev")
rev.Profile = sketch
# ReferenceAxis: We need the Y axis of the sketch or the global Y axis?
# Usually, we reference the axis of the sketch's placement or a global axis.
# Let's use the Y_Axis of the document.
try:
    y_axis = doc.getObject("Y_Axis")
    if not y_axis:
        # Create Y axis if missing
        y_axis = doc.addObject("Part::Line", "Y_Axis")
        y_axis.Placement = App.Placement(App.Vector(0, 0, 0))
        y_axis = y_axis.Shape
    rev.ReferenceAxis = (y_axis, ["Y"])
except:
    # Fallback if axes don't exist, try to use the sketch's own axis or a vector
    # If no axes exist, we can try to use the Z axis of the sketch's placement? 
    # But our sketch is on XY, so Y is vertical.
    # Let's try to create a simple line for the axis if needed.
    rev.ReferenceAxis = (App.Vector(0, 1, 0), ["Y"]) # Vector along Y

rev.Angle = 360.0
rev.Precision = 0.001

# Update the document
doc.recompute()

# Save the file
script_path = Path(__file__).resolve()
output_path = script_path.with_name("answer.FCStd")

doc.saveAs(str(output_path))

print(f"Model generated and saved to: {output_path}")

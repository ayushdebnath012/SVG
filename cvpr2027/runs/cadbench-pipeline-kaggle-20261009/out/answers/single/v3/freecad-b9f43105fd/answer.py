def create_doc():
    """Creates a new FreeCAD document."""
    doc = App.newDocument("PartDesign_Mount")
    return doc

def add_body(doc):
    """Adds a PartDesign Body to the document."""
    body = doc.addObject("PartDesign::Body", "Body")
    body.Placement = App.Placement(App.Vector(0, 0, 0))
    return body

def add_plane(doc, name, vector, axis):
    """Adds a PartDesign Plane to the document."""
    plane = doc.addObject("PartDesign::Plane", name)
    plane.Placement = App.Placement(vector, axis)
    return plane


import cadquery as cq
result = (
    cq.Workplane("XY")
    .circle(2.0)
    .extrude(30.0)
    .faces(">Z").workplane()
    .circle(4.0)
    .extrude(2.4)
    .edges(">Z")
    .fillet(0.48)
    .cut(
        cq.Workplane("XY")
            .transformed(offset=cq.Vector(0, 0, 31.9), rotate=cq.Vector(0, 0, 0))
            .box(8.4, 1.0, 2.2)
    )
    .cut(
        cq.Workplane("XY")
            .transformed(offset=cq.Vector(0, 0, 0), rotate=cq.Vector(90, 0, 0))
            .center(2.0, 0.0)
            .polyline([[0.0, 0.1617], [-0.28, 0.0], [0.0, -0.1617]])
            .close()
            .sweep(cq.Wire.makeHelix(0.7, 14.0, 2.0), isFrenet=False)
    )
)
show_object(result)
import FreeCAD as App
import Part
import Sketcher
from pathlib import Path

# --- Configuration & Parameters ---
# Derived from __file__ as requested
script_dir = Path(__file__).parent
output_path = script_dir / "answer.FCStd"

# Named parameters for the document
L = 500.0  # Length (X)
W = 300.0  # Width (Y)
H = 150.0  # Height (Z)
T = 20.0   # Wall Thickness

# --- Document Creation ---
doc = App.newDocument("Drawer_Parametric")

# 1. Create Parameters
# We create a VarSet to hold the dimensions so they are editable in the tree.
params = doc.addObject("App::VarSet", "Dimensions")
params.addProperty("App::PropertyLength", "Length", "Dimensions", "Outer Length")
params.addProperty("App::PropertyLength", "Width", "Dimensions", "Outer Width")
params.addProperty("App::PropertyLength", "Height", "Dimensions", "Outer Height")
params.addProperty("App::PropertyLength", "Thickness", "Dimensions", "Wall Thickness")
params.Length = L
params.Width = W
params.Height = H
params.Thickness = T

# 2. Create PartDesign Body
body = doc.addObject("PartDesign::Body", "Body")

# 3. Create Base Sketch (Top Face)
# Attached to XY_Plane, defined at left_lower_front_corner (0,0,0)
sketch_top = body.newObject("Sketcher::SketchObject", "TopSketch")
sketch_top.Plane = "XY_Plane"
sketch_top.Support = "XY_Plane"
# Note: In FreeCAD PartDesign, the sketch origin is usually the center of the face.
# To position the corner at (0,0,0), we define the geometry relative to the sketch origin
# and then we can use a placement offset if needed, OR define the sketch origin at the corner.
# The standard XY_Plane in PartDesign Body is at (0,0,0) of the Body.
# So if we draw a rectangle from (0,0) to (L,W), the bottom-left is at (0,0).

sketch_top.addGeometry(Part.LineSegment(App.Vector(0, 0, 0), App.Vector(params.Length.Value, 0, 0)))
sketch_top.addGeometry(Part.LineSegment(App.Vector(0, 0, 0), App.Vector(0, params.Width.Value, 0)))
sketch_top.addGeometry(Part.LineSegment(App.Vector(params.Length.Value, 0, 0), App.Vector(params.Length.Value, params.Width.Value, 0)))
sketch_top.addGeometry(Part.LineSegment(App.Vector(0, params.Width.Value, 0), App.Vector(params.Length.Value, params.Width.Value, 0)))

# Constraints to close the loop and define the rectangle size based on parameters
# Coincident all corners to ensure a closed loop
# Horizontal lines
sketch_top.addConstraint(Sketcher.Constraint("Length", 0, 0, params.Length.Value)) # Line 0-1
sketch_top.addConstraint(Sketcher.Constraint("Length", 2, 3, params.Length.Value)) # Line 2-3
# Vertical lines
sketch_top.addConstraint(Sketcher.Constraint("Length", 0, 1, params.Width.Value))   # Line 0-2
sketch_top.addConstraint(Sketcher.Constraint("Length", 1, 3, params.Width.Value))  # Line 1-3

# Constraint to ensure lines form a rectangle (perpendicularity or 90 deg)
# Or simply constrain the 4 lines to form a closed loop with the lengths defined.
# Let's add perpendicular constraints for robustness.
# Point 0 (0,0)
sketch_top.addConstraint(Sketcher.Constraint("Vertical", 0, 0)) # Line 0 is vertical (Y)
sketch_top.addConstraint(Sketcher.Constraint("Horizontal", 0, 1)) # Line 1 is horizontal (X)
# Point 1 (0, W)
sketch_top.addConstraint(Sketcher.Constraint("Vertical", 0, 1))
sketch_top.addConstraint(Sketcher.Constraint("Horizontal", 0, 2))
# Point 2 (L, W)
sketch_top.addConstraint(Sketcher.Constraint("Vertical", 0, 2))
sketch_top.addConstraint(Sketcher.Constraint("Horizontal", 0, 3))
# Point 3 (L, 0)
sketch_top.addConstraint(Sketcher.Constraint("Vertical", 0, 3))
sketch_top.addConstraint(Sketcher.Constraint("Horizontal", 0, 0))

# 4. Pad the Top Sketch to create the Outer Box
pad_outer = body.newObject("PartDesign::Pad", "PadOuter")
pad_outer.Profile = sketch_top
pad_outer.Length = params.Height.Value
# Pad from bottom up.

# 5. Create Internal Cavity Sketch (On Top Face)
# We need to shell inwards by 'thickness' on all 4 sides.
sketch_inner = body.newObject("Sketcher::SketchObject", "InnerSketch")
sketch_inner.Plane = "TopFace" # The face created by PadOuter
# We need to get the TopFace object reference. 
# In FreeCAD, we can reference the face by name or index, but 'TopFace' is the standard name generated by Pad.
# However, to be safe in a script without GUI, let's rely on the fact that PadOuter creates a face named 'TopFace'.
# Alternatively, we can attach to XY_Plane and lift, but referencing the generated face is cleaner for operations.
# Let's assume the face name is 'TopFace' (standard for PartDesign Pad).
sketch_inner.Plane = "TopFace" 
# We need to calculate the center of the outer body to center our inner sketch.
# Center X = L/2, Center Y = W/2
cx = params.Length.Value / 2.0
cy = params.Width.Value / 2.0

# Inner dimensions
iL = params.Length.Value - (params.Thickness.Value * 2)
iW = params.Width.Value - (params.Thickness.Value * 2)

# Define the rectangle for the cavity opening
# Top-left corner of the inner rect (relative to sketch origin which is now at face center)
# Wait, if Plane is TopFace, the origin of the sketch is the center of that face.
# So we need to offset the geometry by (cx, cy).
# But sketch geometry is defined in the sketcher coordinate system.
# Let's define the lines relative to the sketch origin (0,0) which is the face center.
# The inner box should be centered at (0,0).
# So the rectangle goes from (-iL/2, -iW/2) to (iL/2, iW/2).

sketch_inner.addGeometry(Part.LineSegment(App.Vector(-iL/2, -iW/2, 0), App.Vector(iL/2, -iW/2, 0)))
sketch_inner.addGeometry(Part.LineSegment(App.Vector(iL/2, -iW/2, 0), App.Vector(iL/2, iW/2, 0)))
sketch_inner.addGeometry(Part.LineSegment(App.Vector(iL/2, iW/2, 0), App.Vector(-iL/2, iW/2, 0)))
sketch_inner.addGeometry(Part.LineSegment(App.Vector(-iL/2, iW/2, 0), App.Vector(-iL/2, -iW/2, 0)))

# Constrain the inner rectangle to the center
# Lengths
sketch_inner.addConstraint(Sketcher.Constraint("Length", 0, 0, iL))
sketch_inner.addConstraint(Sketcher.Constraint("Length", 1, 2, iL))
sketch_inner.addConstraint(Sketcher.Constraint("Length", 0, 1, iW))
sketch_inner.addConstraint(Sketcher.Constraint("Length", 1, 3, iW))
# Orientation (Horizontal/Vertical)
sketch_inner.addConstraint(Sketcher.Constraint("Horizontal", 0, 0))
sketch_inner.addConstraint(Sketcher.Constraint("Horizontal", 0, 1))
sketch_inner.addConstraint(Sketcher.Constraint("Vertical", 0, 0))
sketch_inner.addConstraint(Sketcher.Constraint("Vertical", 0, 1))

# 6. Pocket the Inner Sketch to create the Hollow
pocket_inner = body.newObject("PartDesign::Pocket", "PocketInner")
pocket_inner.Profile = sketch_inner
pocket_inner.Type = "ThroughAll"
# Since the sketch is on the top face and we want to hollow out, ThroughAll is correct.

# 7. Shelling (Optional but requested "shell inwards from side walls and bottom")
# The previous steps create an open top box with walls and a bottom.
# The prompt asks for "hollowed internal cavity created by shelling inwards by wall_thickness from the side walls and bottom (top remains open)".
# The "PocketInner" through the top face achieves exactly this: it removes material from the inside of the walls and the bottom.
# This effectively shells the bottom and sides.
# No additional shell feature is needed if the pocket is ThroughAll.

# 8. Save the document
# Ensure all features are computed
doc.recompute()

# Save to the specific path derived from __file__
output_file = output_path
doc.saveAs(str(output_file))

print(f"Model saved to: {output_file}")

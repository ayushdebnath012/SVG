def calc_b(x):
	x = x*1000 #now work in millimetres
	L = 385.0
	b0 = 40.0
	midpoint = L/2

	p1 = (midpoint-40,20)
	p2 = (midpoint-20,20-12.5+1.2)   #1.8
	p3 = (midpoint,20-2.5-1.2)     #1.2
	p4 = (midpoint+20,20-10+1.2)   #1.2
	p5 = (midpoint+40,20)
	points = [p1,p2,p3,p4,p5]
	xs = [p[0] for p in points]
	ys = [p[1] for p in points]

	if x<=midpoint-40 or x> midpoint+40:
		b = b0
	else:    
		if x>midpoint-40 and x<= midpoint-20:
			i = 0
		if x>midpoint-20 and x<= midpoint:
			i = 1
		if x>midpoint and x<= midpoint+20:
			i = 2
		if x>midpoint+20 and x<= midpoint+40:
			i = 3
		
			
			
		x1 = xs[i]
		x2 = xs[i+1]
		y1 = ys[i]
		y2 = ys[i+1]
		
		A = np.array([[x1**3,x1**2,x1,1],[x2**3,x2**2,x2,1],[3*x1**2,2*x1,1,0],[3*x2**2,2*x2,1,0]])
		B = np.array([y1,y2,0,0])
		X = np.linalg.solve(A, B)
		a = X[0]
		b = X[1]
		c = X[2]
		d = X[3]
		

		b = (a*x**3 +b*x**2 +c*x + d)*2
		

	return b/1000   #return in metres

calc_b = np.vectorize(calc_b)





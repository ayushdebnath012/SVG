def calc_alpha(x):
	x = L-x
	alpha = 0.8*(1 - 0.1*x/L   +0.04*(np.cos(11.9*np.pi*x/L) + np.sin(7.2*np.pi*x/L))/(1000*(x/L - 0.5)**6 + 0.2)    + 0.07/(x+0.2)   -0.5*(x/L)*(1-x/L))
	return alpha
calc_alpha = np.vectorize(calc_alpha)

def calc_ky0(x):
	x = L-x
	ky0 = kyo*(1-0.2*x/L)
	return ky0
calc_ky0 = np.vectorize(calc_ky0)

def calc_b(x):
	ky0 = calc_ky0(x)
	alpha = calc_alpha(x)
	b = alpha/ky0
	return b
calc_b = np.vectorize(calc_b)
